# Spin Wheel Predictor experimental computer-vision package (PROMPT 20).
#
# WARNING: this is the most experimental, weakest part of the project. It can
# OBSERVE a physical wheel (estimate angle / when it stops / which segment it
# lands on) -- it does NOT and CANNOT predict the outcome of a future spin. A
# real spin is a chaotic physical process. Treat this as a recording/annotation
# aid, not an oracle.
